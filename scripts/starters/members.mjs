// Builds src/content/starters/members-app.ts from starters/members (stage 180).
//
//   node scripts/starters/members.mjs          writes the module
//   node scripts/starters/members.mjs --check  fails if the module is out of date
//
// The starter's files are real files there, so they can be run and tested as
// they are; the module holds them as strings, with two static snapshots of
// its pages for the template gallery's picture. Edit the files, then run this.
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = fileURLToPath(new URL("../..", import.meta.url));
const source = join(root, "starters", "members");
const target = join(root, "src", "content", "starters", "members-app.ts");

function walk(dir) {
  return readdirSync(dir)
    .filter((name) => name !== "node_modules" && name !== "data")
    .flatMap((name) => {
      const full = join(dir, name);
      return statSync(full).isDirectory() ? walk(full) : [full];
    });
}

// Unix line endings, whatever the checkout uses, so the module is the same on every computer.
const read = (file) => readFileSync(file, "utf8").replace(/\r\n/g, "\n");
const files = walk(source)
  .map((full) => ({ path: relative(source, full).split("\\").join("/"), content: read(full) }))
  .sort((a, b) => (a.path < b.path ? -1 : 1));

// Snapshots for the gallery: the pages as the app renders them, with sample content and no server behind them.
const view = await import(pathToFileURL(join(source, "src", "views.js")).href);
const local = (html) => html.split('href="/styles.css"').join('href="styles.css"');
const sampleUser = { name: "Ama", email: "ama@example.com", createdAt: "2026-11-01T09:00:00.000Z" };
const sampleNotes = [
  { id: "00000000-0000-4000-8000-000000000001", text: "Ship the pricing page on Thursday. Ask about the import.", createdAt: "2026-11-11T09:30:00.000Z" },
  { id: "00000000-0000-4000-8000-000000000002", text: "Books: The Overstory, Piranesi, Klara and the Sun.", createdAt: "2026-11-09T18:10:00.000Z" },
];
const preview = [
  { path: "index.html", content: local(view.home()) },
  { path: "notes.html", content: local(view.notes({ user: sampleUser, csrf: "sample", list: sampleNotes })) },
  { path: "styles.css", content: files.find((f) => f.path === "public/styles.css").content },
];

const lines = (list) => list.map((f) => `  { path: ${JSON.stringify(f.path)}, content: ${JSON.stringify(f.content)} },`).join("\n");
const out = `// Generated by scripts/starters/members.mjs from starters/members. Edit those files, then run the script.
import type { StarterFile } from "./types";

/** The App with sign-in starter (stage 180, ADR 0190): Fieldnote, accounts and private notes in plain Node.js. */
export const MEMBERS_APP_FILES: StarterFile[] = [
${lines(files)}
];

/** Static snapshots of its pages with sample content, for the template gallery's picture. */
export const MEMBERS_APP_PREVIEW: StarterFile[] = [
${lines(preview)}
];
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = read(target);
  } catch {
    // missing counts as out of date
  }
  if (current !== out) {
    console.error("src/content/starters/members-app.ts is out of date. Run: node scripts/starters/members.mjs");
    process.exit(1);
  }
  console.log("members-app.ts is up to date.");
} else {
  writeFileSync(target, out);
  console.log(`Wrote ${relative(root, target)}: ${files.length} files and ${preview.length} preview files.`);
}
