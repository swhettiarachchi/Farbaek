// Farbaek for iPhone takes its colours from the same tokens as the web (ADR 0008, ADR 0110):
// this turns src/styles/tokens.css into ios/Farbaek/Design/Tokens.swift, so the app never has
// colours of its own. tests/design/ios-tokens.test.ts fails when the two drift apart.
// Run: node scripts/ios-tokens.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const TOKENS_CSS = "src/styles/tokens.css";
export const TOKENS_SWIFT = "ios/Farbaek/Design/Tokens.swift";

const camel = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

/** The Swift source for every six-digit colour token in :root, in the stylesheet's order. */
export function swiftTokens(css) {
  const root = css.match(/:root\s*\{([\s\S]*?)\n\}/)?.[1] ?? "";
  const colours = [...root.matchAll(/--([a-z0-9-]+):\s*#([0-9a-f]{6});/gi)].map(([, name, hex]) => ({ name: camel(name), hex: hex.toLowerCase() }));
  if (colours.length === 0) throw new Error("No colour tokens found in tokens.css");
  const lines = colours.map((c) => `    static let ${c.name} = Color(hex: 0x${c.hex})`);
  return [
    "// Generated by scripts/ios-tokens.mjs from src/styles/tokens.css (ADR 0008, ADR 0110). Don't edit by hand.",
    "import SwiftUI",
    "",
    "/// White Signal's colours, the web's tokens exactly. One light theme.",
    "enum Palette {",
    ...lines,
    "}",
    "",
    "extension Color {",
    "    init(hex: UInt32) {",
    "        self.init(.sRGB, red: Double((hex >> 16) & 0xFF) / 255, green: Double((hex >> 8) & 0xFF) / 255, blue: Double(hex & 0xFF) / 255, opacity: 1)",
    "    }",
    "}",
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(TOKENS_SWIFT, swiftTokens(readFileSync(TOKENS_CSS, "utf8")));
  console.log(`Wrote ${TOKENS_SWIFT}`);
}
